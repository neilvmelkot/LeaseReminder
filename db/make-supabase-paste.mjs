#!/usr/bin/env node
/* ============================================================================
 * Bundles the migrations Supabase has not had yet into one paste-ready file.
 *
 * WHY THIS EXISTS
 *   ./db/migrate.sh url "$MIGRATION_DATABASE_URL" is the normal path and
 *   needs the table owner's password — on Supabase that is the project's
 *   database password, which only an operator has. The SQL editor in the
 *   Supabase dashboard is already connected as that owner, so pasting is the
 *   way through when the password is not to hand.
 *
 * USAGE
 *   node db/make-supabase-paste.mjs 0024 0025
 *
 * The output records each file in schema_migrations with the same sha256
 * checksum ./db/migrate.sh computes, so a later run of the script reports
 * them as "skip" rather than trying to apply them a second time.
 * ========================================================================= */

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, "$1"));
const migrationsDir = path.join(here, "migrations");
const prefixes = process.argv.slice(2);

if (prefixes.length === 0) {
  console.error("usage: node db/make-supabase-paste.mjs <prefix> [<prefix>...]");
  process.exit(64);
}

const all = fs.readdirSync(migrationsDir).filter((name) => name.endsWith(".sql")).sort();
const files = [];

for (const prefix of prefixes) {
  const match = all.find((name) => name.startsWith(prefix));

  if (!match) {
    console.error(`error: no migration starts with ${prefix}`);
    process.exit(65);
  }

  files.push(match);
}

const quoted = files.map((name) => `'${name}'`).join(", ");
const sums = files.map((name) => [
  name,
  crypto
    .createHash("sha256")
    .update(fs.readFileSync(path.join(migrationsDir, name)))
    .digest("hex"),
]);

let out = `-- ============================================================================
-- Pending Supabase migrations: ${files.join(", ")}
--
-- HOW TO RUN IT
--   Supabase dashboard -> SQL Editor -> New query -> paste all of this -> Run.
--
-- It is one transaction: either every migration here lands or none does. A
-- second run is refused by the guard below rather than half-applying.
--
-- GENERATED by db/make-supabase-paste.mjs. Do not edit; regenerate instead.
-- ============================================================================

begin;

create table if not exists schema_migrations (
  filename    text primary key,
  checksum    text not null,
  applied_at  timestamptz not null default now(),
  applied_by  text not null default current_user
);

do $pending$
declare
  already text;
begin
  -- Refusing a partial re-run rather than reapplying a migration.
  --
  -- The first version of this guard refused if ANY of the bundle was already
  -- recorded, which is useless when some landed and some did not: it says
  -- "nothing to do" when there is in fact something to do. This one names
  -- what it found, so the next step is obvious.
  select string_agg(filename, ', ' order by filename)
    into already
    from schema_migrations
   where filename in (${quoted});

  if already is not null then
    raise exception
      'Already applied: %. Regenerate this file for the remaining migrations only.',
      already;
  end if;
end
$pending$;
`;

for (const name of files) {
  out += `
-- ============================================================================
-- ${name}
-- ============================================================================

${fs.readFileSync(path.join(migrationsDir, name), "utf8").trimEnd()}
`;
}

out += `
-- -- Ledger -------------------------------------------------------------------
-- The same checksums ./db/migrate.sh computes, so it will report these as
-- "skip" from now on instead of trying to apply them again.

insert into schema_migrations (filename, checksum) values
${sums.map(([name, sum]) => `  ('${name}', '${sum}')`).join(",\n")};

commit;

-- What landed.
select filename, applied_at from schema_migrations
order by filename desc limit ${files.length + 2};
`;

const target = path.join(here, "apply-to-supabase.sql");

fs.writeFileSync(target, out);
console.log(`wrote db/apply-to-supabase.sql (${files.length} migration(s))`);

for (const [name, sum] of sums) {
  console.log(`  ${name}  sha256 ${sum.slice(0, 16)}…`);
}
