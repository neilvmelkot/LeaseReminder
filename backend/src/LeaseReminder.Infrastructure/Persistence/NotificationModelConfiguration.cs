using LeaseReminder.Domain;

using Microsoft.EntityFrameworkCore;

namespace LeaseReminder.Infrastructure.Persistence;

/// <summary>
/// Recipients, groups, and the rules that address a rent reminder.
///
/// <para>
/// In its own file for the same reason the maintenance module is: another
/// two hundred lines inline would bury the lease model AppDbContext exists to
/// describe.
/// </para>
/// </summary>
internal static class NotificationModelConfiguration
{
    public static ModelBuilder ConfigureNotifications(this ModelBuilder modelBuilder)
    {
        ArgumentNullException.ThrowIfNull(modelBuilder);

        modelBuilder.Entity<Recipient>(entity =>
        {
            entity.ToTable("recipients");
            entity.HasKey(e => e.Id);
            entity.Property(e => e.Id).HasColumnName("id");
            entity.Property(e => e.OrganizationId).HasColumnName("organization_id");
            // citext in the database. Mapped explicitly so a lookup by address
            // is case-insensitive on the server rather than only where the
            // caller remembered to lower-case it.
            entity.Property(e => e.Email).HasColumnName("email").HasColumnType("citext");
            entity.Property(e => e.DisplayName).HasColumnName("display_name");
            entity.Property(e => e.TenantId).HasColumnName("tenant_id");
            entity.Property(e => e.Active).HasColumnName("active");
            entity.Property(e => e.CreatedAt).HasColumnName("created_at");
            entity.Property(e => e.UpdatedAt).HasColumnName("updated_at");

            entity.HasIndex(e => new { e.OrganizationId, e.Email }).IsUnique();
        });

        modelBuilder.Entity<RecipientGroup>(entity =>
        {
            entity.ToTable("recipient_groups");
            entity.HasKey(e => e.Id);
            entity.Property(e => e.Id).HasColumnName("id");
            entity.Property(e => e.OrganizationId).HasColumnName("organization_id");
            entity.Property(e => e.Name).HasColumnName("name");
            entity.Property(e => e.Kind).HasColumnName("kind");
            entity.Property(e => e.Description).HasColumnName("description");
            entity.Property(e => e.CreatedAt).HasColumnName("created_at");
            entity.Property(e => e.UpdatedAt).HasColumnName("updated_at");

            entity.HasIndex(e => new { e.OrganizationId, e.Name }).IsUnique();
        });

        modelBuilder.Entity<RecipientGroupMember>(entity =>
        {
            entity.ToTable("recipient_group_members");
            entity.HasKey(e => new { e.RecipientGroupId, e.RecipientId });
            entity.Property(e => e.RecipientGroupId).HasColumnName("recipient_group_id");
            entity.Property(e => e.RecipientId).HasColumnName("recipient_id");
            entity.Property(e => e.OrganizationId).HasColumnName("organization_id");
            entity.Property(e => e.CreatedAt).HasColumnName("created_at");

            // Declared so EF knows a member cannot be inserted before its
            // group. Without it the change tracker has no dependency to order
            // by and is free to send the member first, which the composite
            // foreign key then rejects. No navigation property: the ordering
            // is the only thing wanted here, and an unused navigation is how
            // an accidental join gets written later.
            entity.HasOne<RecipientGroup>()
                .WithMany()
                .HasForeignKey(e => new { e.RecipientGroupId, e.OrganizationId })
                .HasPrincipalKey(e => new { e.Id, e.OrganizationId })
                .OnDelete(DeleteBehavior.Cascade);
        });

        modelBuilder.Entity<NotificationRule>(entity =>
        {
            entity.ToTable("notification_rules");
            entity.HasKey(e => e.Id);
            entity.Property(e => e.Id).HasColumnName("id");
            entity.Property(e => e.OrganizationId).HasColumnName("organization_id");
            entity.Property(e => e.PropertyId).HasColumnName("property_id");
            entity.Property(e => e.LeaseId).HasColumnName("lease_id");

            // Generated by the database from property_id and lease_id. Marked
            // read-only so EF never names it in an INSERT or UPDATE, which
            // Postgres refuses outright for a generated column.
            entity.Property(e => e.Scope)
                .HasColumnName("scope")
                .ValueGeneratedOnAddOrUpdate()
                .Metadata.SetAfterSaveBehavior(
                    Microsoft.EntityFrameworkCore.Metadata.PropertySaveBehavior.Ignore);

            entity.Property(e => e.InheritanceMode).HasColumnName("inheritance_mode");
            entity.Property(e => e.OverridesRuleId).HasColumnName("overrides_rule_id");
            entity.Property(e => e.EventType).HasColumnName("event_type");
            entity.Property(e => e.TriggerType).HasColumnName("trigger_type");
            entity.Property(e => e.OffsetValue).HasColumnName("offset_value");
            entity.Property(e => e.OffsetUnit).HasColumnName("offset_unit");
            entity.Property(e => e.SendLocalTime).HasColumnName("send_local_time");
            entity.Property(e => e.TimeZone).HasColumnName("timezone");
            entity.Property(e => e.QuietHoursStart).HasColumnName("quiet_hours_start");
            entity.Property(e => e.QuietHoursEnd).HasColumnName("quiet_hours_end");
            entity.Property(e => e.DeferOutsideWindow).HasColumnName("defer_outside_window");
            entity.Property(e => e.EmailAccountId).HasColumnName("email_account_id");
            entity.Property(e => e.TemplateId).HasColumnName("template_id");
            entity.Property(e => e.SendSeparately).HasColumnName("send_separately");
            entity.Property(e => e.MaxTotalSends).HasColumnName("max_total_sends");
            entity.Property(e => e.MaxSendsPerDay).HasColumnName("max_sends_per_day");
            entity.Property(e => e.Priority).HasColumnName("priority");
            entity.Property(e => e.Description).HasColumnName("description");
            entity.Property(e => e.Enabled).HasColumnName("enabled");
            entity.Property(e => e.PausedAt).HasColumnName("paused_at");
            entity.Property(e => e.PausedReason).HasColumnName("paused_reason");
            entity.Property(e => e.CreatedAt).HasColumnName("created_at");
            entity.Property(e => e.UpdatedAt).HasColumnName("updated_at");
            entity.Property(e => e.CreatedByUserId).HasColumnName("created_by_user_id");

            entity.HasIndex(e => new { e.OrganizationId, e.EventType });
        });

        modelBuilder.Entity<NotificationRuleRecipient>(entity =>
        {
            entity.ToTable("notification_rule_recipients");
            entity.HasKey(e => e.Id);
            entity.Property(e => e.Id).HasColumnName("id");
            entity.Property(e => e.OrganizationId).HasColumnName("organization_id");
            entity.Property(e => e.NotificationRuleId).HasColumnName("notification_rule_id");
            entity.Property(e => e.RecipientId).HasColumnName("recipient_id");
            entity.Property(e => e.RecipientGroupId).HasColumnName("recipient_group_id");
            entity.Property(e => e.RecipientKind).HasColumnName("recipient_kind");
            entity.Property(e => e.CreatedAt).HasColumnName("created_at");

            // The ordering dependency, and the reason saving a new rule with
            // recipients failed on notification_rule_recipients_rule_fk: with
            // no relationship declared, EF had no idea the target rows depend
            // on the rule row and sent them first.
            entity.HasOne<NotificationRule>()
                .WithMany()
                .HasForeignKey(e => new { e.NotificationRuleId, e.OrganizationId })
                .HasPrincipalKey(e => new { e.Id, e.OrganizationId })
                .OnDelete(DeleteBehavior.Cascade);

            entity.HasIndex(e => e.NotificationRuleId);
        });

        return modelBuilder;
    }
}
