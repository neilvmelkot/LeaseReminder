using FluentValidation;

using LeaseReminder.Domain;

using NodaTime;

namespace LeaseReminder.Api.Endpoints;

/* -------------------------------------------------------------------------- */
/* Recipients                                                                  */
/* -------------------------------------------------------------------------- */

public sealed record RecipientResponse(
    Guid Id,
    string Email,
    string? DisplayName,
    Guid? TenantId,
    string? TenantName,
    /// <summary>
    /// Null when this address is not a tenant's. False is the case worth
    /// surfacing: the address is on a rule and will still be skipped.
    /// </summary>
    bool? TenantOptedIn,
    bool Active,
    int GroupCount,
    int RuleCount);

public sealed record SaveRecipientRequest(
    string Email,
    string? DisplayName,
    Guid? TenantId,
    bool? Active);

public sealed class SaveRecipientRequestValidator : AbstractValidator<SaveRecipientRequest>
{
    public SaveRecipientRequestValidator()
    {
        // The same shape the database CHECK enforces. Validated here too so
        // the answer is a field error rather than a constraint violation.
        RuleFor(request => request.Email)
            .NotEmpty().WithMessage("An email address is required.")
            .MaximumLength(320)
            .Matches(@"^[^\s@]+@[^\s@]+\.[^\s@]+$")
            .WithMessage("That does not look like an email address.");

        RuleFor(request => request.DisplayName)
            .MaximumLength(200)
            .When(request => request.DisplayName is not null);
    }
}

/* -------------------------------------------------------------------------- */
/* Groups                                                                      */
/* -------------------------------------------------------------------------- */

public sealed record RecipientGroupResponse(
    Guid Id,
    string Name,
    string Kind,
    string? Description,
    IReadOnlyList<Guid> RecipientIds,
    int RuleCount);

public sealed record SaveRecipientGroupRequest(
    string Name,
    string? Kind,
    string? Description,
    IReadOnlyList<Guid>? RecipientIds);

public sealed class SaveRecipientGroupRequestValidator
    : AbstractValidator<SaveRecipientGroupRequest>
{
    private static readonly string[] Kinds =
    [
        "landlord", "property_manager", "tenant", "accounting", "maintenance", "custom",
    ];

    public SaveRecipientGroupRequestValidator()
    {
        RuleFor(request => request.Name)
            .NotEmpty().WithMessage("A group needs a name.")
            .MaximumLength(120);

        RuleFor(request => request.Kind)
            .Must(kind => kind is null || Kinds.Contains(kind, StringComparer.Ordinal))
            .WithMessage("That is not a recognised group kind.");

        RuleFor(request => request.Description)
            .MaximumLength(1000)
            .When(request => request.Description is not null);
    }
}

