    Guid? RecipientId,
    Guid? RecipientGroupId,
    RecipientKind RecipientKind);

public sealed record SaveReminderRuleRequest(
    /// <summary>Null for a global rule. Ignored when LeaseId is set.</summary>
    Guid? PropertyId,
    /// <summary>Set for a lease-level rule.</summary>
    Guid? LeaseId,
    RuleInheritanceMode InheritanceMode,
    Guid? OverridesRuleId,
    NotificationEventType EventType,
    NotificationTriggerType TriggerType,
    int OffsetValue,
    OffsetUnit OffsetUnit,
    LocalTime SendLocalTime,
    string? TimeZone,
    bool SendSeparately,
    int? MaxSendsPerDay,
    string? Description,
    bool Enabled,
    IReadOnlyList<SaveRuleTargetRequest>? Targets);

public sealed class SaveReminderRuleRequestValidator
    : AbstractValidator<SaveReminderRuleRequest>
{
    public SaveReminderRuleRequestValidator()
    {
        // An offset only means something with a direction. "On the day"
        // is trigger_type 'on' with offset zero, so a non-zero offset on
        // 'on' is a rule whose author meant something it does not say.
        RuleFor(request => request.OffsetValue)
            .Equal(0)
            .When(request => request.TriggerType == NotificationTriggerType.On)
            .WithMessage("A rule that fires on the day cannot also have an offset.");

        RuleFor(request => request.OffsetValue)
            .GreaterThan(0)
            .When(request => request.TriggerType != NotificationTriggerType.On)
            .WithMessage("Say how far before or after the event this should send.");

        // Guard rail, not arithmetic: an offset in days beyond a year is
        // almost always a typo, and the cost of the typo is mail nobody
        // expected.
        RuleFor(request => request.OffsetValue)
            .LessThanOrEqualTo(365)
            .When(request => request.OffsetUnit == OffsetUnit.Days);

        RuleFor(request => request.MaxSendsPerDay)
            .InclusiveBetween(1, 50)
            .When(request => request.MaxSendsPerDay.HasValue);

        RuleFor(request => request.OverridesRuleId)
            .NotNull()
            .When(request => request.InheritanceMode is RuleInheritanceMode.Overridden
                                 or RuleInheritanceMode.Disabled)
            .WithMessage("Say which inherited rule this one replaces or switches off.");

        // A rule with no targets sends to nobody. It is allowed to exist as a
        // draft -- enabled is separate -- but an ENABLED rule with no targets
        // is silent in a way that looks like it is working.
        RuleFor(request => request.Targets)
            .Must(targets => targets is { Count: > 0 })
            .When(request => request.Enabled)
            .WithMessage("An active rule needs at least one recipient.");

        RuleForEach(request => request.Targets)
            .Must(target => (target.RecipientId is null) != (target.RecipientGroupId is null))
            .WithMessage("Each recipient line is either one person or one group.");

        RuleFor(request => request.Description)
            .MaximumLength(1000)
            .When(request => request.Description is not null);
    }
}
