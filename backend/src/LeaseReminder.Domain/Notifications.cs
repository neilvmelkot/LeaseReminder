using NodaTime;

namespace LeaseReminder.Domain;

/// <summary>
/// Reminder rules and the people they are addressed to.
///
/// <para>
/// These tables were created in migration 0005 and have had Row Level
/// Security and grants since 0009; only the entities were missing, which is
/// why nothing could create a rule and therefore why no rent reminder could
/// be addressed to anybody.
/// </para>
/// </summary>

/// <summary>
/// A reusable email destination.
/// </summary>
/// <remarks>
/// Separate from <see cref="Tenant"/> on purpose. Plenty of the people who
/// should receive a reminder are not tenants — an accountant, a co-owner, a
/// managing agent — and a tenant may have an address that is not the one
/// reminders should go to. <see cref="TenantId"/> links the two when they are
/// the same person, which is what lets the dispatcher honour that tenant's
/// consent.
/// </remarks>
public class Recipient
{
    public Guid Id { get; set; }

    public Guid OrganizationId { get; set; }

    public string Email { get; set; } = string.Empty;

    public string? DisplayName { get; set; }

    /// <summary>
    /// Set when this address belongs to a tenant.
    /// </summary>
    /// <remarks>
    /// The reason it matters is consent: a recipient linked to a tenant who
    /// has opted out of notifications is skipped at send time. An unlinked
    /// address is a business contact and carries no such flag.
    /// </remarks>
    public Guid? TenantId { get; set; }

    /// <summary>
    /// Deactivated rather than deleted, so an existing rule keeps its shape.
    /// </summary>
    public bool Active { get; set; } = true;

    public Instant CreatedAt { get; set; }

    public Instant UpdatedAt { get; set; }
}

/// <summary>
/// A named set of recipients, so a rule can say "the owners" once.
/// </summary>
public class RecipientGroup
{
    public Guid Id { get; set; }

    public Guid OrganizationId { get; set; }

    public string Name { get; set; } = string.Empty;

    /// <summary>
    /// One of landlord, property_manager, tenant, accounting, maintenance,
    /// custom. Free text in the database behind a CHECK rather than an enum,
    /// so it is carried as a string here too.
    /// </summary>
    public string Kind { get; set; } = "custom";

    public string? Description { get; set; }

    public Instant CreatedAt { get; set; }

    public Instant UpdatedAt { get; set; }
}

public class RecipientGroupMember
{
    public Guid RecipientGroupId { get; set; }

    public Guid RecipientId { get; set; }

    public Guid OrganizationId { get; set; }

    public Instant CreatedAt { get; set; }
}

/// <summary>
/// When a reminder goes out, and for what.
/// </summary>
/// <remarks>
/// <para>
/// A rule sits at one of three levels, decided by which of
/// <see cref="PropertyId"/> and <see cref="LeaseId"/> are set: global for the
/// whole workspace, per property, or per lease. The database derives
/// <c>scope</c> from those two columns as a generated column, so the level
/// can never disagree with them.
/// </para>
/// <para>
/// A more specific level does not automatically replace a broader one. What
/// it does is recorded in <see cref="InheritanceMode"/>: an additional rule
/// sends as well as its ancestors, an overriding one replaces the ancestor
/// named by <see cref="OverridesRuleId"/>, and a disabling one switches that
/// ancestor off for this property or lease without deleting anything.
/// </para>
/// </remarks>
public class NotificationRule
{
    public Guid Id { get; set; }

    public Guid OrganizationId { get; set; }

    /// <summary>Set for a property-level or lease-level rule.</summary>
    public Guid? PropertyId { get; set; }

    /// <summary>Set for a lease-level rule only.</summary>
    public Guid? LeaseId { get; set; }

    /// <summary>
    /// Generated by the database from PropertyId and LeaseId. Read-only here:
    /// writing it is not possible, and deriving it in C# would be a second
    /// definition that could drift.
    /// </summary>
    public string Scope { get; set; } = "global";

    public RuleInheritanceMode InheritanceMode { get; set; } = RuleInheritanceMode.Additional;

    /// <summary>The ancestor this rule overrides or disables.</summary>
    public Guid? OverridesRuleId { get; set; }

    public NotificationEventType EventType { get; set; }

    public NotificationTriggerType TriggerType { get; set; }

    /// <summary>How far before or after the event. Zero for "on the day".</summary>
    public int OffsetValue { get; set; }

    public OffsetUnit OffsetUnit { get; set; } = OffsetUnit.Days;

    /// <summary>
    /// The wall-clock time to send at, read in the property's zone.
    /// </summary>
    public LocalTime SendLocalTime { get; set; } = new(9, 0);

    /// <summary>
    /// Null means "use the property's zone at generation time", which is
    /// almost always what is wanted and is why this is nullable rather than
    /// defaulted to the workspace zone.
    /// </summary>
    public string? TimeZone { get; set; }

    public LocalTime? QuietHoursStart { get; set; }

    public LocalTime? QuietHoursEnd { get; set; }

    /// <summary>
    /// Whether a send landing inside quiet hours is moved out of them or
    /// dropped. Moving is the default: a late reminder beats none.
    /// </summary>
    public bool DeferOutsideWindow { get; set; } = true;

    public Guid? EmailAccountId { get; set; }

    public Guid? TemplateId { get; set; }

    /// <summary>
    /// One message each, rather than one message to everybody.
    /// </summary>
    /// <remarks>
    /// Off by default here because the column's default is false, but it is
    /// the setting that stops one tenant seeing another's address in a To
    /// line. The rule editor says so where it is offered.
    /// </remarks>
    public bool SendSeparately { get; set; }

    /// <summary>A hard ceiling on sends this rule may ever produce.</summary>
    public int? MaxTotalSends { get; set; }

    public int MaxSendsPerDay { get; set; } = 10;

    public short Priority { get; set; } = 100;

    public string? Description { get; set; }

    public bool Enabled { get; set; } = true;

    /// <summary>Set when the rule was auto-paused after repeated failures.</summary>
    public Instant? PausedAt { get; set; }

    public string? PausedReason { get; set; }

    public Instant CreatedAt { get; set; }

    public Instant UpdatedAt { get; set; }

    public Guid? CreatedByUserId { get; set; }
}

/// <summary>
/// One target of a rule: a single recipient or a whole group, as to, cc or bcc.
/// </summary>
public class NotificationRuleRecipient
{
    public Guid Id { get; set; }

    public Guid OrganizationId { get; set; }

    public Guid NotificationRuleId { get; set; }

    /// <summary>Exactly one of this and <see cref="RecipientGroupId"/>.</summary>
    public Guid? RecipientId { get; set; }

    public Guid? RecipientGroupId { get; set; }

    public RecipientKind RecipientKind { get; set; } = RecipientKind.To;

    public Instant CreatedAt { get; set; }
}
